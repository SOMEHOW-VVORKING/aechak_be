package com.aechak.application.inspection.port.view;

/**
 * 누락률의 원재료 — "아무도 내용을 보지 않은 채 닫힌 검수"를 센다.
 *
 * <p><b>선별이 위반을 놓친 비율은 여기서 나오지 않는다.</b> 그 분자는 라벨 붙인 정답이고
 * 백엔드에는 정답이 없다 — 재는 자리는 AI 레포의 측정 하네스다. 백엔드가 아는 누락은 둘이다.
 * 판정이 끝내 오지 않거나 실패한 건, 그리고 모델 관점이 하나도 내용을 보지 않은 채 통과로
 * 들어온 건이다. 노출 게이트 스위치가 꺼져 있으면 이 건들이 그대로 노출되므로, 이 수치가
 * "검수를 켜 두고 실제로는 안 본 비율"이다.
 *
 * <p>{@code modelUnverifiedCount}는 <b>게이트가 그 판정을 적용했는지를 다시 센 것</b>이다.
 * 증거가 없는 통과는 게이트 분기를 타지 않아 상품도 큐도 움직이지 않는데, 그 판단은 판정 수신
 * 경로가 메시지에서 계산하고 어디에도 저장하지 않아서 지표가 관점 기록에서 다시 계산할 수밖에
 * 없다. 두 계산이 갈라지면 "지표는 누락이라는데 게이트는 적용한" 상태가 조용히 생기므로,
 * 조회 계층의 접기 규약이 그 함수의 SQL 거울이어야 한다. 등재 사유 같은 파생 상태를 읽지 않는
 * 이유도 같다 — 파생 상태가 원장과 어긋나는 것이 이 기능에서 반복된 결함 모양이다.
 *
 * <p>현 생산자에서 이 수치는 <b>0이어야 한다.</b> AI 서버는 관점 중 하나라도 결과를 낸 것이
 * 있을 때만 통과를 보내고, 전부 미검사면 판정 실패로 내보낸다. 그래서 이 값이 0이 아니면
 * 생산자 결함이 아니라 두 레포의 판정 계약이 갈라졌다는 신호이고, 임계도 그 전제로 잡는다.
 *
 * <p>{@code triageSkippedPassCount}는 선별이 건너뛰어 통과한 건이다. 비율의 분자가 아니라
 * 모집단이다 — 그 가운데 몇 건이 실제 위반이었는지는 사람이 표본을 다시 봐야 알 수 있고,
 * 그 장치(표본 재검)는 선별을 켜는 결정과 함께 다음 범위다. 선별이 건너뛴 건을 사람이 뒤에
 * 막았는지를 세는 대리 지표도 이 범위에 두지 않았다 — 검토 큐 행이 (대상 종류, 대상 id)로만
 * 묶여 있어 다른 내용 때문에 나중에 반려된 건이 잘못 귀속되고, 거짓 분자가 "선별이 놓쳤다"는
 * 가장 위험한 쪽의 확증으로 읽힌다.
 */
public record InspectionCoverageCounts(
        long settledCount,
        long unjudgedCount,
        long verdictFailedCount,
        long modelUnverifiedCount,
        long triageSkippedPassCount) {

    public static InspectionCoverageCounts empty() {
        return new InspectionCoverageCounts(0, 0, 0, 0, 0);
    }
}
